#!/usr/bin/env python3
"""Writes PageLayoutTables.kt, the page tables reading bookmarks are mapped across mushafs with.

Usage: scripts/generate-page-layouts.py <client_bundle.v1.json> [output.kt]

The bundle is Quran.com's mushaf-mapping bundle, `src/utils/mushafMapping/client_bundle.v1.json` in
github.com/quran/quran.com-fe. Every page is `[firstVerseId, lastVerseId]` in canonical Hafs verse ids (1..6236).
Only the four Hafs page groups below are used: the Warsh and Douri groups are numbered differently.
Update SOURCE_COMMIT when generating from another bundle; the revision is read from the bundle.
"""

import json
import sys
from pathlib import Path

SOURCE_URL = "https://github.com/quran/quran.com-fe/blob/{commit}/src/utils/mushafMapping/client_bundle.v1.json"
SOURCE_COMMIT = "8ea017a33588169067c6e99835ffb38c5f16cc9f"
OUTPUT = Path(__file__).resolve().parent.parent / (
    "persistence/src/commonMain/kotlin/com/quran/shared/persistence/repository/readingbookmark/mapping/PageLayoutTables.kt"
)

# (Kotlin object, the bundle's mushafIds for the group, page count, description)
LAYOUTS = [
    ("Madani1440Pages", [1, 4, 5, 16, 19, 23], 604, "The 1440 Madani layout (QCF V2), 604 pages"),
    ("Madani1405Pages", [2, 10, 11, 12], 604, "The 1405 Madani layout (QCF V1), 604 pages"),
    ("IndoPak15LinePages", [6, 14], 610, "The 15-line IndoPak layout, 610 pages as the server numbers them"),
    ("IndoPak16LinePages", [7], 548, "The 16-line IndoPak layout, 548 pages"),
]
VERSES = 6236
PER_LINE = 8


def main() -> None:
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    bundle = json.loads(Path(sys.argv[1]).read_text())
    output = Path(sys.argv[2]) if len(sys.argv) == 3 else OUTPUT
    groups = {tuple(group["mushafIds"]): group["pages"] for group in bundle["pageGroups"]}

    lines = [
        "// Generated by scripts/generate-page-layouts.py. Do not edit.",
        f"// Source: {SOURCE_URL.format(commit=SOURCE_COMMIT)}",
        f"// Revision: {bundle['revision']}",
        "",
        "package com.quran.shared.persistence.repository.readingbookmark.mapping",
        "",
    ]
    for name, mushaf_ids, page_count, description in LAYOUTS:
        pages = groups.get(tuple(mushaf_ids))
        if pages is None:
            sys.exit(f"No page group for mushafs {mushaf_ids}")
        check(name, pages, page_count)
        lines += [
            f"/** {description}: `[firstVerseId, lastVerseId]` per page, flattened. */",
            f"internal object {name} {{",
            "    val ranges = intArrayOf(",
        ]
        for start in range(0, len(pages), PER_LINE):
            chunk = pages[start:start + PER_LINE]
            values = ", ".join(f"{first}, {last}" for first, last in chunk)
            separator = "," if start + PER_LINE < len(pages) else ""
            lines.append(f"        /* {start + 1:3} */ {values}{separator}")
        lines += ["    )", "}", ""]
    output.write_text("\n".join(lines))
    print(f"Wrote {output}")


def check(name: str, pages: list, page_count: int) -> None:
    if len(pages) != page_count:
        sys.exit(f"{name}: {len(pages)} pages, expected {page_count}")
    if pages[0][0] != 1 or pages[-1][1] != VERSES:
        sys.exit(f"{name}: does not cover verses 1 to {VERSES}")
    for (first, last), (next_first, _) in zip(pages, pages[1:]):
        if first > last or next_first not in (last, last + 1):
            sys.exit(f"{name}: pages {first}-{last} and {next_first} are not contiguous")


if __name__ == "__main__":
    main()
