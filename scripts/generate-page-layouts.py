#!/usr/bin/env python3
"""Writes PageLayoutTables.kt, the page tables reading bookmarks are mapped across mushafs with.

Usage: scripts/generate-page-layouts.py <client_bundle.v1.json> [output.kt]

The bundle is Quran.com's mushaf-mapping bundle, `src/utils/mushafMapping/client_bundle.v1.json` in
github.com/quran/quran.com-fe. Every page is `[firstVerseId, lastVerseId]` in canonical Hafs verse ids (1..6236).
Only the four Hafs page groups below are used: the Warsh and Douri groups are numbered differently. Their mushaf ids
are written with their layout (bundleMushafLayouts), and every group's mushaf ids with its page count
(bundleMushafPageCounts), for a test to check ServerMushaf against.
Update SOURCE_COMMIT when generating from another bundle; the revision is read from the bundle.

The Shemerly layout, which the bundle lacks, is read from scripts/data/shemerly-pages.json: the [sura, ayah] each
page starts with, exported from the Android app's page data (the file records its source). A page ends one verse
before the next page starts; the last page ends at the last verse.
"""

import json
import sys
from pathlib import Path

SOURCE_URL = "https://github.com/quran/quran.com-fe/blob/{commit}/src/utils/mushafMapping/client_bundle.v1.json"
SOURCE_COMMIT = "8ea017a33588169067c6e99835ffb38c5f16cc9f"
OUTPUT = Path(__file__).resolve().parent.parent / (
    "persistence/src/commonMain/kotlin/com/quran/shared/persistence/repository/readingbookmark/mapping/PageLayoutTables.kt"
)

# (Kotlin object, PageLayout case, the bundle's mushafIds for the group, page count, description)
LAYOUTS = [
    ("Madani1440Pages", "MADANI_1440", [1, 4, 5, 16, 19, 23], 604, "The 1440 Madani layout (QCF V2), 604 pages"),
    ("Madani1405Pages", "MADANI_1405", [2, 10, 11, 12], 604, "The 1405 Madani layout (QCF V1), 604 pages"),
    ("IndoPak15LinePages", "INDOPAK_15_LINES", [6, 14], 610, "The 15-line IndoPak layout, 610 pages as the server numbers them"),
    ("IndoPak16LinePages", "INDOPAK_16_LINES", [7], 548, "The 16-line IndoPak layout, 548 pages"),
]
# (Kotlin object, page count, description) of the Shemerly layout, read from SHEMERLY_PAGES.
SHEMERLY = ("ShemerlyPages", 521, "The Shemerly layout, 521 pages")
SHEMERLY_PAGES = Path(__file__).resolve().parent / "data/shemerly-pages.json"
VERSES = 6236
# Verses per sura, to turn [sura, ayah] into canonical verse ids.
SURA_VERSES = [
    7, 286, 200, 176, 120, 165, 206, 75, 129, 109, 123, 111, 43, 52, 99, 128, 111, 110, 98, 135,
    112, 78, 118, 64, 77, 227, 93, 88, 69, 60, 34, 30, 73, 54, 45, 83, 182, 88, 75, 85, 54, 53,
    89, 59, 37, 35, 38, 29, 18, 45, 60, 49, 62, 55, 78, 96, 29, 22, 24, 13, 14, 11, 11, 18, 12,
    12, 30, 52, 52, 44, 28, 28, 20, 56, 40, 31, 50, 40, 46, 42, 29, 19, 36, 25, 22, 17, 19, 26,
    30, 20, 15, 21, 11, 8, 8, 19, 5, 8, 8, 11, 11, 8, 3, 9, 5, 4, 7, 3, 6, 3, 5, 4, 5, 6,
]
PER_LINE = 8
LAYOUTS_PER_LINE = 3


def main() -> None:
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    bundle = json.loads(Path(sys.argv[1]).read_text())
    output = Path(sys.argv[2]) if len(sys.argv) == 3 else OUTPUT
    groups = {tuple(group["mushafIds"]): group["pages"] for group in bundle["pageGroups"]}
    shemerly = json.loads(SHEMERLY_PAGES.read_text())

    lines = [
        "// Generated by scripts/generate-page-layouts.py. Do not edit.",
        f"// Source: {SOURCE_URL.format(commit=SOURCE_COMMIT)}",
        f"// Revision: {bundle['revision']}",
        f"// Shemerly: scripts/data/shemerly-pages.json, from {source_url(shemerly['source'])}",
        "",
        "package com.quran.shared.persistence.repository.readingbookmark.mapping",
        "",
    ]
    for name, _, mushaf_ids, page_count, description in LAYOUTS:
        pages = groups.get(tuple(mushaf_ids))
        if pages is None:
            sys.exit(f"No page group for mushafs {mushaf_ids}")
        lines += layout_object(name, pages, page_count, description)
    name, page_count, description = SHEMERLY
    lines += layout_object(name, pages_from_starts(name, shemerly["pageStarts"]), page_count, description)
    lines += mushaf_layouts()
    lines += mushaf_page_counts(bundle["pageGroups"])
    output.write_text("\n".join(lines))
    print(f"Wrote {output}")


def layout_object(name: str, pages: list, page_count: int, description: str) -> list:
    check(name, pages, page_count)
    lines = [
        f"/** {description}: `[firstVerseId, lastVerseId]` per page, flattened. */",
        f"internal object {name} {{",
        "    val ranges = intArrayOf(",
    ]
    for start in range(0, len(pages), PER_LINE):
        chunk = pages[start:start + PER_LINE]
        values = ", ".join(f"{first}, {last}" for first, last in chunk)
        separator = "," if start + PER_LINE < len(pages) else ""
        lines.append(f"        /* {start + 1:3} */ {values}{separator}")
    return lines + ["    )", "}", ""]


def source_url(source: dict) -> str:
    return f"{source['repository']}/blob/{source['commit']}/{source['path']}"


def pages_from_starts(name: str, starts: list) -> list:
    """Pages as [firstVerseId, lastVerseId] from the [sura, ayah] each page starts with."""
    if sum(SURA_VERSES) != VERSES:
        sys.exit("SURA_VERSES does not add up to every verse")
    firsts = []
    for page, (sura, ayah) in enumerate(starts, start=1):
        if not 1 <= sura <= len(SURA_VERSES) or not 1 <= ayah <= SURA_VERSES[sura - 1]:
            sys.exit(f"{name}: page {page} starts at {sura}:{ayah}, which doesn't exist")
        firsts.append(sum(SURA_VERSES[:sura - 1]) + ayah)
    return [[first, last - 1] for first, last in zip(firsts, firsts[1:] + [VERSES + 1])]


def mushaf_layouts() -> list:
    layouts = sorted((mushaf_id, layout) for _, layout, mushaf_ids, _, _ in LAYOUTS for mushaf_id in mushaf_ids)
    entries = [f"{mushaf_id} to PageLayout.{layout}" for mushaf_id, layout in layouts]
    lines = [
        "/** Every mushaf id in the bundle's Hafs page groups, with its page layout. */",
        "internal val bundleMushafLayouts: Map<Int, PageLayout> = mapOf(",
    ]
    for start in range(0, len(entries), LAYOUTS_PER_LINE):
        separator = "," if start + LAYOUTS_PER_LINE < len(entries) else ""
        lines.append(f"    {', '.join(entries[start:start + LAYOUTS_PER_LINE])}{separator}")
    return lines + [")", ""]


def mushaf_page_counts(page_groups: list) -> list:
    counts = {}
    for group in page_groups:
        for mushaf_id in group["mushafIds"]:
            if mushaf_id in counts:
                sys.exit(f"Mushaf {mushaf_id} is in more than one page group")
            counts[mushaf_id] = len(group["pages"])
    entries = [f"{mushaf_id} to {count}" for mushaf_id, count in sorted(counts.items())]
    lines = [
        "/** Every mushaf id in the bundle's page groups, with its group's page count. */",
        "internal val bundleMushafPageCounts: Map<Int, Int> = mapOf(",
    ]
    for start in range(0, len(entries), PER_LINE):
        separator = "," if start + PER_LINE < len(entries) else ""
        lines.append(f"    {', '.join(entries[start:start + PER_LINE])}{separator}")
    return lines + [")", ""]


def check(name: str, pages: list, page_count: int) -> None:
    if len(pages) != page_count:
        sys.exit(f"{name}: {len(pages)} pages, expected {page_count}")
    if pages[0][0] != 1 or pages[-1][1] != VERSES:
        sys.exit(f"{name}: does not cover verses 1 to {VERSES}")
    for (first, last), (next_first, _) in zip(pages, pages[1:]):
        if first > last or next_first not in (last, last + 1):
            sys.exit(f"{name}: pages {first}-{last} and {next_first} are not contiguous")


if __name__ == "__main__":
    main()
